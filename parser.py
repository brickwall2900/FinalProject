import time

# input (str) -> dict[key, value]
def deserialize(serialized):
    ''' 
    Deserialize a parsed serialized string into a Python dictionary.
    Parsed values are parsed line-by-line, finding the pattern &lt;key&gt;=&lt;value&gt;;
    where &lt;key&gt; is the string key of the dictionary, and &lt;value&gt; is the string value of the dictionary.
    '''
    if serialized is None:
        return None
    
    # Checks if the serialized variable is an instance of a string
    if not isinstance(serialized, str):
        return None

    parsed = {}
    for line in serialized.splitlines():
        if line.startswith("#"):
            continue # it's a comment
        
        equals_index = line.find("=")
        # skip if = not found
        if equals_index == -1:
            return None

        key = line[:equals_index]
        value = line[equals_index+1:]
        parsed[key] = value

    return parsed

# input (dict[key]: value) -> str
def serialize(data):
    '''
    Serializes a Python dictionary into a key-value string format.
    Parsed values are output line-by-line, printing the pattern &lt;key&gt;=&lt;value&gt;;
    where &lt;key&gt; is the string key of the dictionary, and &lt;value&gt; is the string value of the dictionary.
    '''
    
    
    # TODO: do we need this?
    # isinstance checks if the instance of `data` is of a given class
    if not isinstance(data, dict): # checks if data is a dict
        return None

    serialized = "# Do NOT edit this file.\n"
    serialized += f"# Serialized: {time.strftime('%Y-%m-%d %H:%M:%S')}\n"
    
    for key in data.keys():
        serialized = serialized + f"{key}={data[key]}\n"

    return serialized
